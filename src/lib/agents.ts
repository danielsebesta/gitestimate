/**
 * AI-agent authorship detection.
 * Sources: CHAOSS disclosure tool, Euthyne detected-signals docs,
 * jphme/github-coding-agent-tracker queries.
 */

export type AgentKind = "agent" | "human";

/**
 * "authored" — the bot identity itself made the commit (author/committer match).
 * "assisted" — a human authored it but an AI tool signed on as co-author/trailer.
 */
export interface AgentSignal {
  strength: "authored" | "assisted";
  via: "author" | "committer" | "trailer";
  /** matched marker pattern, e.g. "devin-ai-integration" */
  marker: string;
}

/** git author / committer identities — matched against login, name, and email */
const AUTHOR_PATTERNS: RegExp[] = [
  /devin-ai-integration/i,
  /@devin\.ai/i,
  /copilot-swe-agent/i,
  /copilot\[bot\]/i,
  /copilot@github\.com/i,
  /copilot(?:\[bot\])?@users\.noreply\.github\.com/i,
  /^copilot(\s*\[bot\])?\s*$/i,
  /\bclaude(?:-code-action)?\[bot\]/i,
  /anthropic-claude/i,
  /^claude(\s*\[bot\])?\s*$/i,
  /noreply@anthropic\.com/i,
  /\bcursor\[bot\]/i,
  /cursoragent/i,
  /cursoragent@cursor\.com/i,
  /openai-codex\[bot\]/i,
  /chatgpt-codex-connector/i,
  /codex@openai\.com/i,
  /noreply@openai\.com/i,
  /google-labs-jules/i,
  /amazon-q-developer/i,
  /jetbrains-(ai|junie)/i,
  /cline[-\w]*\[bot\]/i,
  /continue\[bot\]/i,
  /noreply@continue\.dev/i,
  /sourcegraph-cody/i,
  /openhands/i,
  /all-hands\.dev/i,
  /noreply@opencode\.ai/i,
  /ampcode\.com/i,
  /noreply@codebuff\.com/i,
  /noreply@freebuff\.com/i,
  /noreply@codeium\.com/i,
  /windsurf@codeium\.com/i,
  /noreply@windsurf\.com/i,
  /aider\.chat/i,
  /\(aider\)/i,
  /sweep-ai/i,
  /coderabbit/i,
  /codiumai|pr-agent-pro|qodo/i,
  /gemini-code-assist/i,
  /lovable-dev/i,
  /sourcery-ai/i,
  /greptile/i,
  /tabnine/i,
  /augmentcode|augment-agent/i,
  /kilocode/i,
  /roo[-_]?code/i,
  /trae[-_]agent/i,
  /seer-by-sentry/i,
  /codegen-sh|codegen-ai/i,
  /swe-agent/i,
  // numeric-ID noreply bots survive renames: <id>+<name>@users.noreply.github.com —
  // require the name to actually look like a bot/app ([bot] suffix or tool name + bot|agent|swe|app)
  /\d+\+[^@+]*(?:\[bot\]|(?:claude|copilot|cursor|codex|devin|jules|gemini|cline|cody|openhands|amazon-q|jetbrains|aider|sourcery|greptile|qodo|lovable|amp|windsurf)[-_]?(?:bot|agent|app|swe|dev))[^@]*@users\.noreply\.github\.com/i,
  /sourcegraph.*bot/i,
  // any other GitHub-app bot identity as author/committer — automation, not human time
  /\[bot\]/i,
];

/** co-author trailer value — tested against AUTHOR_PATTERNS, not loose substrings */
const COAUTHOR_TRAILER = /^co-?authored-?by:\s*(.+?)\s*$/gim;

/** RFC-822 trailers and footer lines inside the commit message body */
const MESSAGE_PATTERNS: RegExp[] = [
  /assisted-by:/i,
  /generated with \[?claude/i,
  /generated with claude code/i,
  /generated with (?:codebuff|freebuff|v0)/i,
  /generated with:\s+github\.com\/[^@]*(?:codebuff|freebuff)/i,
  /made[- ]with:? ?cursor/i,
  /generated by (?:jules|devin|codex|copilot)/i,
  /claude-session:/i,
  /agent-logs-url:/i,
  /replit-commit-(author|session-id):/i,
  /amp-thread-id:/i,
  /^entire-(metadata|session|checkpoint|agent|strategy|condensation|source-ref)/im,
  /^aider:\s/m,
  /automated security fix.*orbis/i,
  /chatgpt\.com\/codex\/(cloud\/)?tasks\//i,
  /pr created automatically by jules/i,
  /<!--\s*(generated by replit ai|generated by v0|v0 by vercel|cursor_summary|windsurf)\s*-->/i,
  /<!--\s*generated with aider\s*-->/i,
];

export function detectCommit(fields: {
  author?: string;
  authorEmail?: string;
  committer?: string;
  committerEmail?: string;
  message?: string;
}): AgentSignal | null {
  for (const [via, val] of [
    ["author", `${fields.author ?? ""} ${fields.authorEmail ?? ""}`],
    ["committer", `${fields.committer ?? ""} ${fields.committerEmail ?? ""}`],
  ] as const) {
    const m = AUTHOR_PATTERNS.find((p) => p.test(val));
    if (m) return { strength: "authored", via, marker: m.source };
  }
  if (fields.message) {
    COAUTHOR_TRAILER.lastIndex = 0;
    let co: RegExpExecArray | null;
    while ((co = COAUTHOR_TRAILER.exec(fields.message))) {
      const p = AUTHOR_PATTERNS.find((r) => r.test(co![1]));
      if (p) return { strength: "assisted", via: "trailer", marker: `co-author ${p.source}` };
    }
    const m = MESSAGE_PATTERNS.find((p) => p.test(fields.message!));
    if (m) return { strength: "assisted", via: "trailer", marker: m.source };
  }
  return null;
}

/** repo file paths that signal AI tooling in use */
const FILE_PATTERNS: Array<[RegExp, string]> = [
  [/^\.?agents\.md$/i, "AGENTS.md"],
  [/^\.?claude\.md$/i, "CLAUDE.md"],
  [/^\.claude\//i, ".claude/"],
  [/^\.cursor\//i, ".cursor/"],
  [/^\.cursorrules$/i, ".cursorrules"],
  [/^\.windsurf/i, ".windsurf"],
  [/^\.github\/copilot-instructions\.md$/i, "copilot-instructions.md"],
  [/^\.github\/instructions\//i, ".github/instructions/"],
  [/^\.aider/i, ".aider"],
  [/^\.cline/i, ".cline"],
  [/^\.roo/i, ".roo"],
  [/^\.continue\//i, ".continue/"],
  [/^\.openhands/i, ".openhands"],
  [/^\.devin\//i, ".devin/"],
  [/^\.codex\//i, ".codex/"],
  [/^\.jules\//i, ".jules/"],
  [/^\.gemini\//i, ".gemini/"],
  [/^gemini\.md$/i, "GEMINI.md"],
  [/^\.qwen\//i, ".qwen/"],
  [/^\.?claude[._-]?local\.md$/i, "CLAUDE.local.md"],
  [/^\.kiro\//i, ".kiro/"],
  [/^\.trae\//i, ".trae/"],
  [/^\.amazonq\//i, ".amazonq/"],
  [/^\.junie\//i, ".junie/"],
  [/^\.augment\//i, ".augment/"],
  [/^\.kilocode\//i, ".kilocode/"],
  [/^\.qodo\//i, ".qodo/"],
  [/^\.lovable\//i, ".lovable/"],
];

export function detectFiles(paths: string[]): string[] {
  const found = new Set<string>();
  for (const p of paths)
    for (const [re, label] of FILE_PATTERNS) if (re.test(p)) found.add(label);
  return [...found];
}
